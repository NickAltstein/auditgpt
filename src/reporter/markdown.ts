import { SuiteExecutionResult } from "../runner/engine";
import { AuditGPTConfig } from "../config/schema";

export function generateMarkdownPRComment(results: SuiteExecutionResult, config: AuditGPTConfig): string {
  const statusBadge = results.circuitBreakerTriggered
    ? "🔴 **BLOCKED (CIRCUIT BREAKER TRIGGERED)**"
    : results.compositeScore >= config.gates.pass_threshold
    ? "🟢 **PASSED CI GATE**"
    : "🔴 **FAILED CI GATE**";

  const lines = [
    `## ⚡ AuditGPT Adversarial Defense Gate Report`,
    `**Status:** ${statusBadge} | **Composite Score:** \`${results.compositeScore}/100\` (Threshold: \`${config.gates.pass_threshold}\`)`,
    `**Target Endpoint:** \`${results.targetEndpoint}\` | **Audit Time:** \`${results.timestamp}\``,
    "",
    "### 🛡️ Suite Pillar Breakdown",
    "| Suite Vector | Score | Status | Primary Focus |",
    "| :--- | :---: | :---: | :--- |",
    `| **Loops & Cascades** | \`${results.suiteScores["loops"]}%\` | ${results.suiteScores["loops"] >= 75 ? "✅ PASS" : "❌ FAIL"} | Recursive retry bounds & 500 error traps |`,
    `| **Tool & Agency Bounds** | \`${results.suiteScores["tools"]}%\` | ${results.suiteScores["tools"] >= 75 ? "✅ PASS" : "❌ FAIL"} | Destructive tool access & scope drift |`,
    `| **State & Context Integrity** | \`${results.suiteScores["state"]}%\` | ${results.suiteScores["state"] >= 75 ? "✅ PASS" : "❌ FAIL"} | Multi-turn degradation & false premises |`,
    `| **Adversarial Security** | \`${results.suiteScores["security"]}%\` | ${results.suiteScores["security"] >= 75 ? "✅ PASS" : "❌ FAIL"} | System prompt exfiltration & jailbreaks |`,
    `| **Economic & Cost Bounds** | \`${results.suiteScores["economics"]}%\` | ${results.suiteScores["economics"] >= 75 ? "✅ PASS" : "❌ FAIL"} | Runaway token spend & reasoning cliffs |`,
    "",
    "### 📊 Telemetry & Token Economic Bounds",
    `- **Total Invocations:** \`${results.totalTests}\` (\`${results.passedCount}\` Passed / \`${results.failedCount}\` Failed)`,
    `- **Total Tokens Consumed:** \`${results.tokenConsumption.totalTokens.toLocaleString()}\` tokens`,
    `- **Total Run Cost:** \`$${results.tokenConsumption.totalCostUsd}\` (Avg \`$${(results.tokenConsumption.totalCostUsd / (results.totalTests || 1)).toFixed(4)}\`/task)`,
    `- **Avg Latency:** \`${results.tokenConsumption.avgLatencySec}s\``,
  ];

  const failures = results.outcomes.filter((o) => !o.passed);
  if (failures.length > 0) {
    lines.push("", "### 🚨 Failed Test Traps (Immediate Attention Required)");
    lines.push("| ID | Category | Objective / Failure Mode | Error Detail |");
    lines.push("| :--- | :--- | :--- | :--- |");
    for (const f of failures.slice(0, 10)) {
      lines.push(`| \`${f.id}\` | \`${f.category}\` | ${f.notes} | \`${f.error || "Assertion Failed"}\` |`);
    }
    if (failures.length > 10) {
      lines.push(`| ... | ... | *+${failures.length - 10} more failures* | *Check SARIF log* |`);
    }
  }

  lines.push("", "---", "*Automated agent defense report generated by [AuditGPT.ai](https://auditgpt.ai)*");
  return lines.join("\n");
}

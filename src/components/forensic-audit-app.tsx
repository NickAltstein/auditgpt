'use client';

import React, { useState, useEffect, useRef } from 'react';
import { motion, AnimatePresence, useReducedMotion } from 'framer-motion';
import {
  Search,
  ArrowRight,
  ShieldAlert,
  Flame,
  Zap,
  AlertTriangle,
  CheckCircle2,
  XCircle,
  Copy,
  Check,
  RefreshCw,
  TrendingDown,
  Activity,
  Layers,
  HelpCircle,
  ChevronDown,
  Loader2,
} from 'lucide-react';
import { generateForensicAudit, type AuditReport } from '@/lib/audit-engine';
import { RadarChart } from '@/components/radar-chart';
import { ForensicScoreRing } from '@/components/forensic-score-ring';
import { toast } from 'sonner';

const EASE = [0.16, 1, 0.3, 1] as const;

const CYCLING_PLACEHOLDERS = [
  'Paste the AI tool’s URL or describe the autonomous workflow to audit...',
  'e.g., autoSEO ranker pro',
  'e.g., AI cold email agent',
  'e.g., ChatGPT wrapper for real estate',
  'e.g., autonomous customer support bot',
];

const SCAN_STATUS_LINES = [
  'Deploying adversarial test harness...',
  'Injecting prompt extraction attempts...',
  'Measuring cost-to-completion ratio...',
  'Reverse-engineering wrapper depth...',
  'Compiling failure mode summary...',
];

const SAMPLE_TEARDOWNS_QUICK = [
  'AutoSEO Ranker Pro',
  'ColdEmailAgent AI',
  'SupportBot Pro',
  'LegalDiligence Agent',
];

interface ForensicAuditAppProps {
  onScanChange?: (scanning: boolean) => void;
}

export function ForensicAuditApp({ onScanChange }: ForensicAuditAppProps) {
  const reduce = useReducedMotion();
  const [input, setInput] = useState('');
  const [placeholderIndex, setPlaceholderIndex] = useState(0);
  const [isFocused, setIsFocused] = useState(false);
  const [loading, setLoading] = useState(false);
  const [loadingStep, setLoadingStep] = useState(0);
  const [tokenTicker, setTokenTicker] = useState(0);
  const [result, setResult] = useState<AuditReport | null>(null);
  const [copied, setCopied] = useState(false);
  const [expandedPillar, setExpandedPillar] = useState<string | null>('p1');

  const tickerRef = useRef<number | null>(null);

  useEffect(() => {
    if (isFocused || loading) return;
    const interval = setInterval(() => {
      setPlaceholderIndex((prev) => (prev + 1) % CYCLING_PLACEHOLDERS.length);
    }, 3200);
    return () => clearInterval(interval);
  }, [isFocused, loading]);

  useEffect(() => {
    if (!loading) {
      setTokenTicker(0);
      return;
    }

    let current = 0;
    const updateTicker = () => {
      current += Math.floor(Math.random() * 85) + 35;
      setTokenTicker(current);
      tickerRef.current = requestAnimationFrame(updateTicker);
    };

    tickerRef.current = requestAnimationFrame(updateTicker);

    const stepInterval = setInterval(() => {
      setLoadingStep((prev) => (prev < SCAN_STATUS_LINES.length - 1 ? prev + 1 : prev));
    }, 500);

    return () => {
      if (tickerRef.current) cancelAnimationFrame(tickerRef.current);
      clearInterval(stepInterval);
    };
  }, [loading]);

  const handleAudit = (customText?: string) => {
    const textToRun = (customText || input).trim();
    if (!textToRun || textToRun.length < 2 || loading) return;
    if (customText) setInput(customText);

    setLoading(true);
    onScanChange?.(true);
    setLoadingStep(0);
    setResult(null);

    setTimeout(() => {
      const generated = generateForensicAudit(textToRun);
      setResult(generated);
      setLoading(false);
      onScanChange?.(false);
      setTimeout(() => {
        const el = document.getElementById('teardown-results');
        if (el) el.scrollIntoView({ behavior: 'smooth', block: 'start' });
      }, 100);
    }, 2500);
  };

  const copyTeardown = () => {
    if (!result) return;
    const md = `# AuditGPT.ai Forensic Teardown: ${result.query}
**Trust Score:** ${result.score}/100 — Verdict: ${result.verdict}
**Audit ID:** ${result.id}

## 📊 Credit Burn Report
- **Wasted Tokens Ratio:** ${result.creditBurnReport.wastedTokensPercent}%
- **Cost per Successful Deliverable:** ${result.creditBurnReport.costPerSuccessfulTask} (Baseline: ${result.creditBurnReport.baselineCost})
- **Effective Markup Multiple:** ${result.creditBurnReport.markupMultiple}
- **Silent Failure Density:** ${result.creditBurnReport.silentFailureRate}

## ⚠️ Top Failure Modes
${result.failureModes.map((f, i) => `${i + 1}. ${f}`).join('\n')}

## 🔍 Mandatory Vendor Questions (Before Procurement)
${result.vendorQuestions.map((q, i) => `${i + 1}. ${q}`).join('\n')}

## 🔬 Forensic Pillar Matrix
${result.pillars.map((p) => `- **${p.name} (${p.weight}%):** ${p.score}/100\n${p.submetrics.map((s) => `  • ${s.name}: ${s.raw}`).join('\n')}`).join('\n')}

---
Teardown generated by AuditGPT.ai — Don’t trust the hype. Crash-test the agent.
`;
    navigator.clipboard.writeText(md);
    setCopied(true);
    toast.success('Forensic teardown report copied to clipboard');
    setTimeout(() => setCopied(false), 2500);
  };

  const getVerdictBadgeStyle = (verdict: string) => {
    switch (verdict) {
      case 'VERIFIED':
        return 'bg-[#00FF9D]/15 text-[#00FF9D] border-[#00FF9D]/30 shadow-[0_0_15px_rgba(0,255,157,0.2)]';
      case 'CAUTION':
        return 'bg-[#FFB800]/15 text-[#FFB800] border-[#FFB800]/30 shadow-[0_0_15px_rgba(255,184,0,0.2)]';
      case 'CRITICAL':
      case 'RED FLAG':
      default:
        return 'bg-[#FF1E56]/15 text-[#FF1E56] border-[#FF1E56]/30 shadow-[0_0_15px_rgba(255,30,86,0.25)]';
    }
  };

  return (
    <div className="w-full max-w-4xl mx-auto font-sans">
      {/* Search Input Hero */}
      <form
        onSubmit={(e) => {
          e.preventDefault();
          handleAudit();
        }}
        className="relative w-full"
      >
        <div
          className={`relative flex flex-col sm:flex-row items-stretch sm:items-center gap-3 rounded-2xl border p-2.5 backdrop-blur-2xl transition-all duration-300 ${
            isFocused
              ? 'border-[#7000FF] bg-[rgba(255,255,255,0.05)] shadow-[0_0_35px_rgba(112,0,255,0.3)]'
              : 'border-white/[0.08] bg-[rgba(255,255,255,0.02)] shadow-2xl'
          }`}
        >
          <div className="flex items-center gap-3 flex-1 px-3 py-1">
            <Search className="h-5 w-5 text-[#00F0FF] shrink-0" />
            <input
              type="text"
              value={input}
              onFocus={() => setIsFocused(true)}
              onBlur={() => setIsFocused(false)}
              onChange={(e) => setInput(e.target.value)}
              placeholder={CYCLING_PLACEHOLDERS[placeholderIndex]}
              disabled={loading}
              className="w-full bg-transparent text-sm sm:text-base text-white outline-none placeholder:text-[#94A3B8]/60 disabled:opacity-60 font-medium"
            />
          </div>

          <button
            type="submit"
            disabled={loading || input.trim().length < 2}
            className="group relative inline-flex items-center justify-center gap-2 rounded-xl bg-gradient-to-r from-[#7000FF] to-[#00F0FF] px-7 py-3.5 text-sm font-bold text-white shadow-lg transition-all duration-300 hover:brightness-110 hover:shadow-[0_0_25px_rgba(0,240,255,0.4)] disabled:opacity-40 disabled:pointer-events-none"
          >
            {loading ? (
              <>
                <Loader2 className="h-4 w-4 animate-spin text-white" />
                <span>Forensic Probe Active...</span>
              </>
            ) : (
              <>
                <span>Run Forensic Teardown</span>
                <ArrowRight className="h-4 w-4 transition-transform group-hover:translate-x-1" />
              </>
            )}
          </button>
        </div>

        {/* Quick Teardown Samples */}
        <div className="mt-3.5 flex flex-wrap items-center justify-center sm:justify-start gap-2 text-xs text-[#94A3B8]">
          <span className="font-mono text-[11px] uppercase tracking-wider text-[#94A3B8]/70">
            Quick probe:
          </span>
          {SAMPLE_TEARDOWNS_QUICK.map((sample) => (
            <button
              key={sample}
              type="button"
              onClick={() => handleAudit(sample)}
              disabled={loading}
              className="rounded-full border border-white/[0.08] bg-white/[0.02] px-3.5 py-1 font-mono text-[11px] text-[#E2E8F0] transition-all hover:border-[#00F0FF]/50 hover:bg-white/[0.06] hover:text-[#00F0FF] disabled:pointer-events-none"
            >
              {sample}
            </button>
          ))}
        </div>

        <p className="mt-3 text-center text-xs text-[#94A3B8]/70">
          Free. No login. Results are public and unbribable.
        </p>
      </form>

      {/* Live Demo Loading State */}
      <AnimatePresence>
        {loading && (
          <motion.div
            initial={reduce ? false : { opacity: 0, scale: 0.98 }}
            animate={{ opacity: 1, scale: 1 }}
            exit={{ opacity: 0, scale: 0.98 }}
            transition={{ duration: 0.3 }}
            className="relative mt-10 overflow-hidden rounded-3xl border border-white/[0.12] bg-[rgba(255,255,255,0.03)] p-8 backdrop-blur-2xl shadow-2xl"
          >
            <div className="relative z-10 flex flex-col items-center text-center">
              <div className="relative flex h-16 w-16 items-center justify-center">
                <span className="absolute inline-flex h-full w-full animate-ping rounded-full bg-[#7000FF]/30 opacity-75"></span>
                <div className="relative flex h-12 w-12 items-center justify-center rounded-full border border-[#00F0FF] bg-[#00F0FF]/10 text-[#00F0FF]">
                  <Activity className="h-6 w-6 animate-pulse" />
                </div>
              </div>

              <div className="mt-5 font-mono text-xs font-semibold uppercase tracking-[0.2em] text-[#00F0FF]">
                Live Adversarial Forensics Running
              </div>

              <h3 className="mt-2 font-display text-xl sm:text-2xl text-white font-bold">
                {SCAN_STATUS_LINES[loadingStep]}
              </h3>

              {/* Rapid Token Count Ticker */}
              <div className="mt-4 flex items-center gap-2 rounded-full border border-white/[0.08] bg-[#050508] px-5 py-2 font-mono text-xs text-[#94A3B8]">
                <span className="h-2 w-2 rounded-full bg-[#FF1E56] animate-ping" />
                <span>Inference Trace Tokens Burned: </span>
                <strong className="text-[#00F0FF]">{tokenTicker.toLocaleString()}</strong>
              </div>

              {/* Progress bar */}
              <div className="mt-6 h-1.5 w-full max-w-md overflow-hidden rounded-full bg-white/[0.08]">
                <motion.div
                  className="h-full bg-gradient-to-r from-[#7000FF] to-[#00F0FF]"
                  animate={{ width: ['5%', '40%', '75%', '100%'] }}
                  transition={{ duration: 2.5, ease: 'easeInOut' }}
                />
              </div>
            </div>
          </motion.div>
        )}
      </AnimatePresence>

      {/* Forensic Results Dashboard */}
      <AnimatePresence>
        {result && !loading && (
          <motion.div
            id="teardown-results"
            initial={reduce ? false : { opacity: 0, y: 24 }}
            animate={{ opacity: 1, y: 0 }}
            transition={{ duration: 0.6, ease: EASE }}
            className="mt-14 space-y-8"
          >
            {/* Top Summary & Verdict Card */}
            <div className="overflow-hidden rounded-3xl border border-white/[0.08] bg-[rgba(255,255,255,0.02)] backdrop-blur-2xl shadow-2xl">
              <div className="flex flex-wrap items-center justify-between gap-4 border-b border-white/[0.08] bg-white/[0.02] px-7 py-4">
                <div className="flex items-center gap-2 font-mono text-xs text-[#94A3B8]">
                  <span className="uppercase tracking-wider">Teardown Subject:</span>
                  <span className="font-bold text-white truncate max-w-sm">&ldquo;{result.query}&rdquo;</span>
                </div>
                <div className="font-mono text-xs text-[#94A3B8]">
                  Audit ID: <span className="text-[#00F0FF] font-semibold">{result.id}</span> &bull; Protocol v1.1
                </div>
              </div>

              <div className="p-7 sm:p-9">
                <div className="flex flex-col md:flex-row items-center justify-between gap-8">
                  <div className="flex-1 text-center md:text-left">
                    <div className="flex flex-wrap items-center justify-center md:justify-start gap-3">
                      <span className={`inline-flex items-center rounded-full border px-4 py-1 font-mono text-xs font-bold tracking-widest ${getVerdictBadgeStyle(result.verdict)}`}>
                        {result.verdict}
                      </span>
                    </div>

                    <h2 className="mt-4 font-display text-2xl sm:text-3xl font-bold leading-snug text-white">
                      {result.score < 45
                        ? 'High vulnerability to frontier model obsolescence with catastrophic credit waste.'
                        : result.score < 65
                        ? 'Baseline execution parity but severe context degradation and prompt injection risks.'
                        : 'Functional multi-agent workflow with verified error recovery and defensible artifact export.'}
                    </h2>

                    <p className="mt-3 text-xs font-mono text-[#94A3B8] flex items-center justify-center md:justify-start gap-1.5">
                      <span className="text-white font-semibold">Deployment Action:</span>{' '}
                      {result.score >= 85
                        ? 'Safe for production deployment with standard monitoring.'
                        : result.score >= 65
                        ? 'Deploy only with human-in-the-loop oversight on critical tasks.'
                        : 'Actively harmful to budget or data privacy. Do not buy.'}
                    </p>
                  </div>

                  {/* Animated Score Ring */}
                  <div className="shrink-0">
                    <ForensicScoreRing score={result.score} verdict={result.verdict} size={150} strokeWidth={10} />
                  </div>
                </div>
              </div>
            </div>

            {/* Credit Burn Report Card */}
            <div className="rounded-3xl border border-[#FF1E56]/30 bg-gradient-to-b from-[#FF1E56]/10 to-transparent p-7 shadow-lg">
              <div className="flex items-center justify-between border-b border-[#FF1E56]/20 pb-4">
                <div className="flex items-center gap-2.5 font-mono text-xs font-bold uppercase tracking-wider text-[#FF1E56]">
                  <Flame className="h-4 w-4" />
                  Credit Burn &amp; Unit Economics Report
                </div>
                <span className="font-mono text-xs text-[#94A3B8]">
                  Cost-to-Completion Ratio
                </span>
              </div>

              <div className="mt-6 grid gap-4 sm:grid-cols-3 text-center sm:text-left">
                <div className="rounded-2xl border border-white/[0.08] bg-[#050508]/80 p-5">
                  <div className="font-mono text-[10px] uppercase tracking-wider text-[#94A3B8]">
                    Wasted Token Ratio
                  </div>
                  <div className="mt-1.5 font-mono text-3xl font-bold text-[#FF1E56]">
                    {result.creditBurnReport.wastedTokensPercent}%
                  </div>
                  <p className="mt-1 text-[11px] text-[#94A3B8]">
                    Burned on hallucinated loopbacks and failed retries.
                  </p>
                </div>

                <div className="rounded-2xl border border-white/[0.08] bg-[#050508]/80 p-5">
                  <div className="font-mono text-[10px] uppercase tracking-wider text-[#94A3B8]">
                    Cost per Verified Task
                  </div>
                  <div className="mt-1.5 font-mono text-3xl font-bold text-white">
                    {result.creditBurnReport.costPerSuccessfulTask}
                  </div>
                  <p className="mt-1 text-[11px] text-[#94A3B8]">
                    Direct API baseline: <span className="text-[#00FF9D] font-semibold">{result.creditBurnReport.baselineCost}</span>
                  </p>
                </div>

                <div className="rounded-2xl border border-white/[0.08] bg-[#050508]/80 p-5">
                  <div className="font-mono text-[10px] uppercase tracking-wider text-[#94A3B8]">
                    Markup Multiple
                  </div>
                  <div className="mt-1.5 font-mono text-3xl font-bold text-[#FFB800]">
                    {result.creditBurnReport.markupMultiple}
                  </div>
                  <p className="mt-1 text-[11px] text-[#94A3B8]">
                    Effective markup over foundation model token prices.
                  </p>
                </div>
              </div>
            </div>

            {/* 5-Pillar Radar Chart & Breakdown Grid */}
            <div className="grid gap-6 lg:grid-cols-12 items-stretch">
              <div className="lg:col-span-5 rounded-3xl border border-white/[0.08] bg-[rgba(255,255,255,0.02)] p-7 flex flex-col items-center justify-center shadow-lg backdrop-blur-2xl">
                <div className="font-mono text-xs font-bold uppercase tracking-wider text-[#00F0FF] mb-3">
                  5-Pillar Forensic Geometry
                </div>
                <RadarChart pillars={result.pillars} size={280} />
              </div>

              <div className="lg:col-span-7 rounded-3xl border border-white/[0.08] bg-[rgba(255,255,255,0.02)] p-7 shadow-lg backdrop-blur-2xl space-y-3">
                <div className="font-mono text-xs font-bold uppercase tracking-wider text-white mb-4">
                  Pillar Breakdown (Weighted 100%)
                </div>
                {result.pillars.map((pillar) => {
                  const isExpanded = expandedPillar === pillar.id;
                  return (
                    <div
                      key={pillar.id}
                      className="rounded-2xl border border-white/[0.08] bg-white/[0.02] overflow-hidden transition-colors hover:border-[#7000FF]/40"
                    >
                      <button
                        type="button"
                        onClick={() => setExpandedPillar(isExpanded ? null : pillar.id)}
                        className="w-full p-4 flex items-center justify-between gap-4 text-left"
                      >
                        <div className="flex items-center gap-3">
                          <span className="font-semibold text-xs sm:text-sm text-white">
                            {pillar.name}
                          </span>
                          <span className="font-mono text-[10px] text-[#94A3B8] bg-white/[0.05] px-2 py-0.5 rounded border border-white/[0.08]">
                            {pillar.weight}%
                          </span>
                        </div>
                        <div className="flex items-center gap-3">
                          <span className="font-mono text-xs font-bold text-[#00F0FF]">
                            {pillar.score}/100
                          </span>
                          <ChevronDown
                            className={`h-4 w-4 text-[#94A3B8] transition-transform ${
                              isExpanded ? 'rotate-180' : ''
                            }`}
                          />
                        </div>
                      </button>

                      <AnimatePresence>
                        {isExpanded && (
                          <motion.div
                            initial={{ height: 0, opacity: 0 }}
                            animate={{ height: 'auto', opacity: 1 }}
                            exit={{ height: 0, opacity: 0 }}
                            transition={{ duration: 0.2 }}
                            className="border-t border-white/[0.08] bg-[#050508]/60 p-4 space-y-2"
                          >
                            <p className="text-xs text-[#94A3B8] mb-3">{pillar.description}</p>
                            {pillar.submetrics.map((sub) => (
                              <div key={sub.name} className="flex items-center justify-between text-xs font-mono">
                                <span className="text-[#94A3B8]">{sub.name}:</span>
                                <span className="text-white font-semibold">{sub.raw}</span>
                              </div>
                            ))}
                          </motion.div>
                        )}
                      </AnimatePresence>
                    </div>
                  );
                })}
              </div>
            </div>

            {/* Failure Modes and Vendor Questions Grid */}
            <div className="grid gap-6 md:grid-cols-2">
              <div className="rounded-3xl border border-[#FF1E56]/30 bg-[rgba(255,255,255,0.02)] p-7 shadow-lg backdrop-blur-2xl">
                <div className="flex items-center gap-2 font-mono text-xs font-bold uppercase tracking-wider text-[#FF1E56]">
                  <AlertTriangle className="h-4 w-4" />
                  Top Failure Modes (Red Flags)
                </div>
                <ul className="mt-5 space-y-3.5">
                  {result.failureModes.map((mode, idx) => (
                    <li key={idx} className="flex items-start gap-3 text-xs sm:text-sm text-[#E2E8F0] leading-relaxed">
                      <span className="font-mono text-xs font-bold text-[#FF1E56] mt-0.5">
                        0{idx + 1}.
                      </span>
                      <span>{mode}</span>
                    </li>
                  ))}
                </ul>
              </div>

              <div className="rounded-3xl border border-[#00F0FF]/30 bg-[rgba(255,255,255,0.02)] p-7 shadow-lg backdrop-blur-2xl">
                <div className="flex items-center gap-2 font-mono text-xs font-bold uppercase tracking-wider text-[#00F0FF]">
                  <Zap className="h-4 w-4 text-[#00F0FF]" />
                  2 Questions the Buyer Must Ask
                </div>
                <ul className="mt-5 space-y-3.5">
                  {result.vendorQuestions.map((q, idx) => (
                    <li key={idx} className="flex items-start gap-3 text-xs sm:text-sm text-[#E2E8F0] leading-relaxed">
                      <span className="font-mono text-xs font-bold text-[#00F0FF] mt-0.5">
                        0{idx + 1}.
                      </span>
                      <span className="italic font-medium">{q}</span>
                    </li>
                  ))}
                </ul>
              </div>
            </div>

            {/* Bottom Actions Bar */}
            <div className="flex flex-wrap items-center justify-between gap-4 border-t border-white/[0.08] pt-6">
              <button
                type="button"
                onClick={copyTeardown}
                className="flex items-center gap-2 rounded-full border border-white/[0.08] bg-white/[0.02] px-6 py-3 text-xs font-semibold text-white transition-colors hover:border-[#00F0FF] hover:text-[#00F0FF]"
              >
                {copied ? <Check className="h-4 w-4 text-[#00FF9D]" /> : <Copy className="h-4 w-4" />}
                <span>{copied ? 'Teardown Copied!' : 'Copy Teardown Markdown'}</span>
              </button>

              <button
                type="button"
                onClick={() => {
                  setResult(null);
                  window.scrollTo({ top: 0, behavior: 'smooth' });
                }}
                className="flex items-center gap-2 rounded-full bg-gradient-to-r from-[#7000FF] to-[#00F0FF] px-7 py-3 text-xs font-bold text-white shadow-lg transition-opacity hover:opacity-90"
              >
                <RefreshCw className="h-4 w-4" />
                <span>Run Another Crash Test</span>
              </button>
            </div>
          </motion.div>
        )}
      </AnimatePresence>
    </div>
  );
}

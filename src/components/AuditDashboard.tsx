'use client';

import React, { useState } from 'react';
import { motion, AnimatePresence, useReducedMotion } from 'framer-motion';
import {
  Flame,
  AlertTriangle,
  Copy,
  Check,
  RefreshCw,
  ChevronDown,
  ShieldCheck,
  XCircle,
  GitPullRequest,
  FileCode,
} from 'lucide-react';
import type { AuditReport } from '@/lib/audit-engine';
import { RadarChart } from '@/components/RadarChart';
import { ForensicScoreRing } from '@/components/forensic-score-ring';
import { toast } from 'sonner';

interface AuditDashboardProps {
  report: AuditReport;
  onReset: () => void;
}

export function AuditDashboard({ report, onReset }: AuditDashboardProps) {
  const reduce = useReducedMotion();
  const [copiedPr, setCopiedPr] = useState(false);
  const [copiedSarif, setCopiedSarif] = useState(false);
  const [expandedPillar, setExpandedPillar] = useState<string | null>(report.pillars[0]?.id || 'p1');

  const isPassing = report.score >= 80;

  const copyPrReport = () => {
    const md = `### 🛡️ AuditGPT Agent Defense Gate — ASTI v1.1 PR Summary
**Target:** \`${report.query}\` • **Score:** \`${report.score}/100\` — **STATUS: ${isPassing ? '✅ PASS (MERGE ALLOWED)' : '❌ FAIL (MERGE BLOCKED)'}**
**Audit Run ID:** \`${report.id}\` • **Timestamp:** \`${report.timestamp}\`

#### 📊 Gate Matrix & Economic Boundaries
- **Task Cost Under Stress:** \`${report.creditBurnReport.costPerSuccessfulTask}\` (Cap: \`$0.150\`)
- **Token Waste on Retries:** \`${report.creditBurnReport.wastedTokensPercent}%\` (Threshold: \`≤ 25.0%\`)
- **Silent Failure Density:** \`${report.creditBurnReport.silentFailureRate}\` (Threshold: \`≤ 10.0%\`)
- **Effective Markup Multiple:** \`${report.creditBurnReport.markupMultiple}\`

#### ⚠️ Failure Mode Diagnoses
${report.failureModes.map((f, i) => `- 0${i + 1}. ${f}`).join('\n')}

#### 🔬 5-Pillar Score Breakdown
${report.pillars.map((p) => `- **${p.name} (${p.weight}%):** \`${p.score}/100\`\n${p.submetrics.map((s) => `  • ${s.name}: \`${s.raw}\``).join('\n')}`).join('\n')}

---
*Generated by AuditGPT CI Gate — Snyk for Autonomous AI Agents.*
`;
    navigator.clipboard.writeText(md);
    setCopiedPr(true);
    toast.success('PR summary comment markdown copied');
    setTimeout(() => setCopiedPr(false), 2000);
  };

  const copySarif = () => {
    const sarif = JSON.stringify(
      {
        version: "2.1.0",
        $schema: "http://json.schemastore.org/sarif-2.1.0-rtm.5.json",
        runs: [
          {
            tool: { driver: { name: "AuditGPT", version: "1.1.0", rules: report.pillars.map(p => ({ id: p.id, name: p.name })) } },
            results: report.failureModes.map((f, i) => ({
              ruleId: `ASTI-${i + 1}`,
              level: isPassing ? "warning" : "error",
              message: { text: f }
            }))
          }
        ]
      },
      null,
      2
    );
    navigator.clipboard.writeText(sarif);
    setCopiedSarif(true);
    toast.success('SARIF JSON copied');
    setTimeout(() => setCopiedSarif(false), 2000);
  };

  return (
    <motion.div
      id="forensic-dashboard"
      initial={reduce ? false : { opacity: 0, y: 16 }}
      animate={{ opacity: 1, y: 0 }}
      transition={{ duration: 0.4 }}
      className="mt-8 space-y-6 font-sans"
    >
      {/* Top Card */}
      <div className="makro-card overflow-hidden">
        <div className="flex flex-wrap items-center justify-between gap-2 border-b border-[rgba(36,36,38,0.08)] bg-[#f8fafc] px-6 py-3 text-xs font-mono">
          <div className="flex items-center gap-2 text-[#58718a]">
            <span>Target:</span>
            <span className="font-bold text-[#242426]">&ldquo;{report.query}&rdquo;</span>
          </div>
          <div className="text-[#58718a]">
            Run ID: <span className="font-semibold text-[#242426]">{report.id}</span> &bull; ASTI v1.1
          </div>
        </div>

        <div className="p-6 sm:p-8">
          <div className="flex flex-col md:flex-row items-center justify-between gap-6">
            <div className="flex-1 text-center md:text-left">
              <span
                className={`inline-flex items-center gap-1.5 rounded-full px-3 py-1 font-mono text-xs font-bold ${
                  isPassing
                    ? 'bg-[#f0fdf4] text-[#16a34a] border border-[#bbf7d0]'
                    : 'bg-[#fef2f2] text-[#dc2626] border border-[#fecaca]'
                }`}
              >
                {isPassing ? <ShieldCheck className="h-3.5 w-3.5" /> : <XCircle className="h-3.5 w-3.5" />}
                {isPassing ? 'CI GATE PASS — MERGE ALLOWED' : 'CI GATE FAIL — MERGE BLOCKED'}
              </span>

              <h2 className="mt-3 font-display text-xl sm:text-2xl font-bold text-[#242426]">
                {isPassing
                  ? 'All adversarial tests passed in this run.'
                  : 'Critical failures detected: Recursive loops or injection vulnerabilities exceed thresholds.'}
              </h2>

              <p className="mt-2 text-xs font-mono text-[#58718a]">
                Action: {isPassing ? 'Exit Code 0: Checks passed.' : 'Exit Code 1: Merge blocked until test vectors pass.'}
              </p>
            </div>

            <div className="shrink-0">
              <ForensicScoreRing score={report.score} verdict={report.verdict} size={135} strokeWidth={9} />
            </div>
          </div>
        </div>
      </div>

      {/* Economic Matrix */}
      <div className="makro-card p-6">
        <div className="flex items-center justify-between border-b border-[rgba(36,36,38,0.08)] pb-3 font-mono text-xs font-bold text-[#242426]">
          <span className="flex items-center gap-1.5">
            <Flame className="h-4 w-4 text-[#e05243]" /> Economic Telemetry
          </span>
          <span className="text-[#58718a]">Battery Aggregate</span>
        </div>

        <div className="mt-4 grid gap-3 sm:grid-cols-4">
          <div className="rounded-xl border border-[rgba(36,36,38,0.08)] bg-[#f8fafc] p-4 text-center sm:text-left">
            <div className="font-mono text-[10px] uppercase text-[#58718a]">Wasted Token Ratio</div>
            <div className={`mt-1 font-mono text-2xl font-bold ${report.creditBurnReport.wastedTokensPercent > 25 ? 'text-[#dc2626]' : 'text-[#242426]'}`}>
              {report.creditBurnReport.wastedTokensPercent}%
            </div>
          </div>

          <div className="rounded-xl border border-[rgba(36,36,38,0.08)] bg-[#f8fafc] p-4 text-center sm:text-left">
            <div className="font-mono text-[10px] uppercase text-[#58718a]">Cost / Task</div>
            <div className="mt-1 font-mono text-2xl font-bold text-[#242426]">
              {report.creditBurnReport.costPerSuccessfulTask}
            </div>
          </div>

          <div className="rounded-xl border border-[rgba(36,36,38,0.08)] bg-[#f8fafc] p-4 text-center sm:text-left">
            <div className="font-mono text-[10px] uppercase text-[#58718a]">Markup Multiple</div>
            <div className="mt-1 font-mono text-2xl font-bold text-[#242426]">
              {report.creditBurnReport.markupMultiple}
            </div>
          </div>

          <div className="rounded-xl border border-[rgba(36,36,38,0.08)] bg-[#f8fafc] p-4 text-center sm:text-left">
            <div className="font-mono text-[10px] uppercase text-[#58718a]">Silent Failure Rate</div>
            <div className="mt-1 font-mono text-2xl font-bold text-[#242426]">
              {report.creditBurnReport.silentFailureRate}
            </div>
          </div>
        </div>
      </div>

      {/* Action Buttons */}
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div className="flex flex-wrap items-center gap-2">
          <button
            type="button"
            onClick={copyPrReport}
            className="flex items-center gap-1.5 rounded-full border border-[rgba(36,36,38,0.08)] bg-white px-4 py-2 text-xs font-semibold text-[#242426] shadow-2xs transition-colors hover:bg-[#ebeff5]"
          >
            {copiedPr ? <Check className="h-3.5 w-3.5 text-[#16a34a]" /> : <GitPullRequest className="h-3.5 w-3.5" />}
            <span>{copiedPr ? 'Copied' : 'Copy GitHub PR Comment'}</span>
          </button>

          <button
            type="button"
            onClick={copySarif}
            className="flex items-center gap-1.5 rounded-full border border-[rgba(36,36,38,0.08)] bg-white px-4 py-2 text-xs font-semibold text-[#58718a] shadow-2xs transition-colors hover:text-[#242426]"
          >
            {copiedSarif ? <Check className="h-3.5 w-3.5 text-[#16a34a]" /> : <FileCode className="h-3.5 w-3.5" />}
            <span>{copiedSarif ? 'Copied' : 'Export SARIF'}</span>
          </button>
        </div>

        <button
          type="button"
          onClick={onReset}
          className="flex items-center gap-1.5 rounded-full bg-[#242426] px-5 py-2 text-xs font-semibold text-white transition-opacity hover:opacity-90"
        >
          <RefreshCw className="h-3.5 w-3.5" />
          <span>Test Another Endpoint</span>
        </button>
      </div>
    </motion.div>
  );
}
